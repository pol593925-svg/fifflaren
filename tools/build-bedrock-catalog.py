"""Build the compact rules table from Mojang bedrock-samples (1.26.60.5).
Only identifiers, names, ingredient combinations and counts are exported.
Usage: python tools/build-bedrock-catalog.py <bedrock-samples checkout> <output.js>
"""
import collections
import json
import re
import sys
from pathlib import Path

source, output = map(Path, sys.argv[1:])
version = json.loads((source/'version.json').read_text())['latest']['version']
if version != '1.26.60.5':
    raise ValueError('Expected Bedrock 1.26.60.5; review identifiers before upgrading')
def read(path):
    raw = re.sub(r'("(?:\\.|[^"\\])*")|//[^\n\r]*|/\*[\s\S]*?\*/', lambda m: m[1] or '', path.read_text(encoding='utf-8-sig'))
    return json.loads(re.sub(r',\s*(?=[}\]])', '', raw))
def bare(s):
    return s.removeprefix('minecraft:')
def item(value):
    if isinstance(value, dict):
        if 'tag' in value:
            return '#'+bare(value['tag'])
        name, data = bare(value['item']), value.get('data',0)
    else:
        name, data = bare(value), 0
        if re.search(r':-?\d+$',name):
            name, data = name.rsplit(':',1)
            data = int(data)
    if name.startswith('potion_type:'):name=name.lower()
    if name in ('boat','chest_boat') and 0 <= data < 8:
        return ('oak','spruce','birch','jungle','acacia','dark_oak','mangrove','bamboo')[data]+'_'+name
    if name=='dye' and 0<=data<=19:
        return ('ink_sac','red_dye','green_dye','cocoa_beans','lapis_lazuli','purple_dye','cyan_dye','light_gray_dye','gray_dye','pink_dye','lime_dye','yellow_dye','light_blue_dye','magenta_dye','orange_dye','bone_meal','black_dye','brown_dye','blue_dye','white_dye')[data]
    if name=='bucket' and data==1:return 'milk_bucket'
    if name=='coal' and data==1:return 'charcoal'
    if name=='bamboo_planks':return name
    if name=='wool' and data==0:return 'white_wool'
    if data not in (0,-1):return name+':'+str(data)
    return name
def lang(code):
    kv={}
    for line in (source/'resource_pack/texts'/code).read_text(encoding='utf-8-sig').splitlines():
        k,sep,v=line.partition('=')
        if sep:kv[k]=v.split('##')[0].strip()
    return kv
ru, en = lang('ru_RU.lang'), lang('en_US.lang')
names, labels, blocks = set(), {}, set()
for category in ['items','blocks']:
    for d in read(source/'metadata/vanilladata_modules'/('mojang-'+category+'.json'))['data_items']:
        n=bare(d['name'])
        names.add(n)
        if category=='blocks':blocks.add(n)
        for key in [d['serialization_id']+'.name', 'item.'+n+'.name','tile.'+n+'.name']:
            if ru.get(key) and '%' not in ru[key]:labels[n]=ru[key];break
        if n not in labels:
            labels[n]=next((ru[k] for k,v in en.items() if v.casefold()==n.replace('_',' ').casefold() and ru.get(k)),n.replace('_',' '))
rules=[]
for f in sorted((source/'behavior_pack/recipes').glob('*.json')):
    obj=read(f); key,r=next((k,v) for k,v in obj.items() if k.startswith('minecraft:'))
    typ=key.split('recipe_')[1]
    if typ=='shaped':
        slots=[[item(r['key'][v]) if v!=' ' else '' for v in row] for row in r['pattern']]
    elif typ=='shapeless':
        slots=[[item(v) for v in r['ingredients'] for _ in range(v.get('count',1) if isinstance(v,dict) else 1)]]
    elif typ=='furnace':slots=[[item(r['input'])]]
    elif typ.startswith('brewing'):slots=[[item(r['input']),item(r['reagent'])]]
    else:slots=[[item(r[x]) for x in ('template','base','addition')]]
    result=r.get('result',r.get('output',[]))
    results=collections.Counter()
    for v in (result if isinstance(result,list) else [result]):
        results[item(v)]+=v.get('count',1) if isinstance(v,dict) else 1
    for n in [*results,*sum(slots,[])]:
        if n and not n.startswith('#'):names.add(n)
    rules.append([f.stem,typ,r['tags'],slots,results,r.get('priority',0)])
data={'version':version,'entries':[[n,labels.get(n,n.replace('_',' ')),int(n in blocks)] for n in sorted(names)],'rules':rules}
wrapper="// Gameplay facts from Mojang/bedrock-samples @15701fa9; generated by build-bedrock-catalog.py.\n(function(root){const data="+json.dumps(data,ensure_ascii=False,separators=(',',':'))+";if(typeof module==='object'&&module.exports)module.exports=data;if(root)root.HubBedrockData=data;})(typeof window==='undefined'?null:window);\n"
output.write_text(wrapper,encoding='utf-8')
print('Bedrock:',version,'blocks:',len(blocks),'entries:',len(names),'rules:',len(rules))
